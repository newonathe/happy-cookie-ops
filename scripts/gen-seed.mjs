#!/usr/bin/env node
/**
 * Regenerates supabase/seed.sql from the engine's own constants.
 *
 * The seed claims to hold "exactly the numbers the design shows". This script is what
 * makes that claim checkable: it reads PRODUCTS, INVENTORY, SUPPLIERS, PACK_SIZE,
 * RECIPES and USE_BY_DAYS straight out of src/store/engine/ops-engine.js and writes the
 * SQL. A hand-edited seed drifts from the design silently, which is how you end up
 * demoing prices the owner has never charged.
 *
 * Run after any change to those constants:  node scripts/gen-seed.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const engine = readFileSync(join(ROOT, 'src/store/engine/ops-engine.js'), 'utf8');

/** Reads one top-level `const NAME = <literal>;` out of the engine. */
function literal(name) {
  const start = engine.indexOf(`const ${name} =`);
  if (start < 0) throw new Error(`${name} not found in the engine`);
  const end = engine.slice(start).match(/\n(\]|\});/);
  if (!end) throw new Error(`could not find the end of ${name}`);
  const body = engine.slice(start + `const ${name} =`.length, start + end.index + 2);
  return Function(`return (${body})`)();
}

const PRODUCTS = literal('PRODUCTS');
const INVENTORY = literal('INVENTORY');
const SUPPLIERS = literal('SUPPLIERS');
const PACK_SIZE = literal('PACK_SIZE');
const RECIPES = literal('RECIPES');
const USE_BY_DAYS = literal('USE_BY_DAYS');
const ALLERGENS = literal('ALLERGENS');

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
/**
 * Must match pesosToCentavos() in src/lib/money.ts exactly. Duplicated rather than
 * imported because this is a plain node script with no bundler and money.ts is a TS
 * module — but the rounding is the load-bearing part (38.44 * 100 is 3843.9999999999995),
 * and tests/unit/money-conversion.test.ts is what proves the shared behaviour.
 */
const cents = (pesos) => Math.round(pesos * 100);
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const supplierNames = new Set([...SUPPLIERS.map((s) => s.name), ...INVENTORY.map((i) => i.supplier)]);
const id = {};
for (const name of supplierNames) id[name] = slug(name);

const out = [];
const section = (title) => out.push('', `-- ${title} ${'-'.repeat(Math.max(0, 74 - title.length))}`);

out.push(
  '-- Seed for local development.',
  '--',
  "-- GENERATED by scripts/gen-seed.mjs from the engine's own constants. Do not hand-edit:",
  '-- change the engine, then re-run the generator.',
  '--',
  "-- Money is centavos. Quantities are the item's own unit (g, ml, pcs), never rounded."
);

section('suppliers');
out.push('insert into suppliers (id, name, place) values');
out.push(
  [...supplierNames]
    .map((name) => {
      const s = SUPPLIERS.find((x) => x.name === name);
      return `  (${q(id[name])}, ${q(name)}, ${q(s ? s.place : '')})`;
    })
    .join(',\n') + '\non conflict (id) do nothing;'
);

section('catalogue');
out.push(
  'insert into products (id, name, short_name, price_cents, kind, tag, description, image_path, sort_order) values'
);
out.push(
  PRODUCTS.map(
    (p, i) =>
      '  (' +
      [q(p.id), q(p.name), q(p.short), cents(p.price), q(p.kind), q(p.tag || ''), q(p.desc), q('/' + p.img), i + 1].join(', ') +
      ')'
  ).join(',\n') + '\non conflict (id) do nothing;'
);

section('stock');
out.push(
  'insert into inventory_items (id, category, name, unit, on_hand, par_level, pack_size, supplier_id, use_by_days, last_counted) values'
);
out.push(
  INVENTORY.map((item) => {
    const pack = PACK_SIZE[item.name];
    const useBy = USE_BY_DAYS[item.name];
    return (
      '  (' +
      [
        q(slug(item.name)), q(item.cat), q(item.name), q(item.unit),
        item.qty, item.level,
        pack == null ? 'null' : pack,
        q(id[item.supplier]),
        useBy == null ? 'null' : useBy,
        `now() - interval '${item.agoD} days'`
      ].join(', ') +
      ')'
    );
  }).join(',\n') + '\non conflict (id) do nothing;'
);

section('supplier price book');
const prices = [];
for (const supplier of SUPPLIERS) {
  for (const line of supplier.items) {
    prices.push(
      '  (' +
        [
          q(id[supplier.name]), q(line.item), q(line.pack), cents(line.price),
          `'{${(line.prev || []).map(cents).join(',')}}'`,
          q(line.last || ''), line.preferred ? 'true' : 'false'
        ].join(', ') +
        ')'
    );
  }
}
out.push(
  'insert into supplier_prices (supplier_id, item_name, pack_label, price_cents, previous_cents, last_bought, preferred) values'
);
out.push(prices.join(',\n') + '\non conflict (supplier_id, item_name) do nothing;');

section('recipes');
out.push('insert into recipes (product_id, yield_count) values');
out.push(
  Object.entries(RECIPES).map(([pid, r]) => `  (${q(pid)}, ${r.yield})`).join(',\n') +
    '\non conflict (product_id) do nothing;'
);
out.push('');
const ingredients = [];
for (const [pid, recipe] of Object.entries(RECIPES)) {
  for (const [name, qty, unit] of recipe.ing) {
    ingredients.push(`  (${q(pid)}, ${q(name)}, ${qty}, ${q(unit)})`);
  }
}
out.push('insert into recipe_ingredients (product_id, item_name, qty, unit) values');
out.push(ingredients.join(',\n') + ';');
out.push('');

// MP-09 c1: allergens joined the flavour record (migration 20260101003000). Appended as
// one statement at the end, so the rows above keep their reviewed bytes; the block is a
// registered reversal in scripts/validate-g0.py.
out.push(
  '-- allergens (MP-09 c1)',
  'update products set allergens = v.allergens from (values',
  Object.entries(ALLERGENS).map(([pid, text]) => `  (${q(pid)}, ${q(text)})`).join(',\n'),
  ') as v (id, allergens) where products.id = v.id;',
  ''
);

writeFileSync(join(ROOT, 'supabase/seed.sql'), out.join('\n'));
console.log(
  `seed.sql written — ${supplierNames.size} suppliers, ${PRODUCTS.length} products, ` +
    `${INVENTORY.length} stock items, ${prices.length} supplier prices, ` +
    `${Object.keys(RECIPES).length} recipes, ${ingredients.length} ingredients`
);
